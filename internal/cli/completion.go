// topCommands drives both the completion scripts and the test that keeps them
// in step with the real command dispatch.
var topCommands = []struct{ name, desc string }{
	{"doctor", "scan this PC and explain what limits it"},
	{"status", "one-screen summary and pending recovery"},
	{"network", "layer-by-layer network diagnosis"},
	{"tweaks", "list or show the optimizations"},
	{"apply", "apply optimizations (id=value)"},
	{"preset", "ready-made bundles: gaming, desktop, network, maximum"},
	{"undo", "undo the most recent change"},
	{"snapshots", "restore points: list, show, restore, recover"},
	{"benchmark", "import and compare benchmark logs"},
	{"game", "launch options and wrapped game runs"},
	{"completion", "print a shell completion script (bash or fish)"},
}

const completionUsage = "usage: turbo completion bash|fish\n" +
	"  bash: turbo completion bash > ~/.local/share/bash-completion/completions/turbo\n" +
	"  fish: turbo completion fish > ~/.config/fish/completions/turbo.fish\n"

func cmdCompletion(args []string, o *out) int {
	if len(args) != 1 {
		fmt.Fprint(o.err, completionUsage)
		return ExitUsage
	}
	switch args[0] {
	case "bash":
		fmt.Fprint(o.w, bashCompletion())
	case "fish":
		fmt.Fprint(o.w, fishCompletion())
	default:
		fmt.Fprintf(o.err, "turbo: no completion for %q\n%s", args[0], completionUsage)
		return ExitUsage
	}
	return ExitOK
}

// cmdComplete is the hidden `turbo __complete <kind>` the scripts call for
// values that depend on this machine. It prints one candidate per line and
// never fails loudly: a broken completion must not spray errors into a prompt.
func cmdComplete(ctx context.Context, a *app.App, args []string, o *out) int {
	if len(args) != 1 {
		return ExitUsage
	}
	var list []string
	switch args[0] {
	case "tweaks", "tweak-values":
		for _, t := range a.Reg.All() {
			id := t.Meta().ID
			if args[0] == "tweak-values" {
				id += "="
			}
			list = append(list, id)
		}
	case "presets":
		for _, p := range tweaks.Presets() {
			list = append(list, p.ID)
		}
	case "snapshots":
		if snaps, _, err := a.Store.List(); err == nil {
			for _, s := range snaps {
				list = append(list, s.ID)
			}
		}
	default:
		return ExitUsage
	}
	sort.Strings(list)
	for _, s := range list {
		fmt.Fprintln(o.w, s)
	}
	return ExitOK
}

func bashCompletion() string {
	var names []string
	for _, c := range topCommands {
		names = append(names, c.name)
	}
	return `# bash completion for turbo (TurboShift). Generated by: turbo completion bash
_turbo() {
    local cur prev sub
    cur=${COMP_WORDS[COMP_CWORD]}
    prev=${COMP_WORDS[COMP_CWORD-1]}
    sub=${COMP_WORDS[1]}
    # '=' is a word break in bash; leave the value after id= to the user.
    if [[ $cur == "=" || $prev == "=" ]]; then return; fi
    if (( COMP_CWORD == 1 )); then
        COMPREPLY=( $(compgen -W "` + strings.Join(names, " ") + ` --help --version" -- "$cur") )
        return
    fi
    case $sub in
        tweaks)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "list show" -- "$cur") )
            elif [[ ${COMP_WORDS[2]} == show ]]; then
                COMPREPLY=( $(compgen -W "$(turbo __complete tweaks 2>/dev/null)" -- "$cur") )
            else
                COMPREPLY=( $(compgen -W "--all --json" -- "$cur") )
            fi ;;
        apply)
            COMPREPLY=( $(compgen -W "$(turbo __complete tweak-values 2>/dev/null) --dry-run --yes" -- "$cur") )
            compopt -o nospace 2>/dev/null ;;
        preset)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "list show apply" -- "$cur") )
            elif [[ ${COMP_WORDS[2]} == apply ]]; then
                COMPREPLY=( $(compgen -W "$(turbo __complete presets 2>/dev/null) --dry-run --yes" -- "$cur") )
            else
                COMPREPLY=( $(compgen -W "$(turbo __complete presets 2>/dev/null)" -- "$cur") )
            fi ;;
        undo)
            COMPREPLY=( $(compgen -W "--yes" -- "$cur") ) ;;
        snapshots)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "list show restore recover" -- "$cur") )
            else
                COMPREPLY=( $(compgen -W "$(turbo __complete snapshots 2>/dev/null) --force --json" -- "$cur") )
            fi ;;
        doctor)    COMPREPLY=( $(compgen -W "--json --top" -- "$cur") ) ;;
        network)   COMPREPLY=( $(compgen -W "--external --target --lookup --json" -- "$cur") ) ;;
        benchmark) COMPREPLY=( $(compgen -W "import list compare find" -- "$cur") ) ;;
        game)      COMPREPLY=( $(compgen -W "options run" -- "$cur") ) ;;
        completion) COMPREPLY=( $(compgen -W "bash fish" -- "$cur") ) ;;
    esac
}
complete -F _turbo turbo
`
}

func fishCompletion() string {
	var b strings.Builder
	b.WriteString("# fish completion for turbo (TurboShift). Generated by: turbo completion fish\n")
	b.WriteString("complete -c turbo -f\n")
	b.WriteString("complete -c turbo -n __fish_use_subcommand -l help -d 'show help'\n")
	b.WriteString("complete -c turbo -n __fish_use_subcommand -l version -d 'show the version'\n")
	for _, c := range topCommands {
		fmt.Fprintf(&b, "complete -c turbo -n __fish_use_subcommand -a %s -d '%s'\n", c.name, c.desc)
	}
	// The word after a command, when it has fixed sub-commands.
	for _, s := range []struct{ cmd, word, desc string }{
		{"tweaks", "list", "what can be changed on this PC"},
		{"tweaks", "show", "details, risks and how to measure one tweak"},
		{"preset", "list", "list the presets"},
		{"preset", "show", "preview what a preset would change here"},
		{"preset", "apply", "apply a preset (asks first)"},
		{"snapshots", "list", "list restore points"},
		{"snapshots", "show", "show one restore point"},
		{"snapshots", "restore", "put a restore point back"},
		{"snapshots", "recover", "finish or undo an interrupted change"},
		{"benchmark", "import", "import a MangoHud/CSV log"},
		{"benchmark", "list", "list imported runs"},
		{"benchmark", "compare", "compare two labelled runs"},
		{"benchmark", "find", "find MangoHud logs on this PC"},
		{"game", "options", "print Steam launch options"},
		{"game", "run", "run a game with the chosen wrappers"},
		{"completion", "bash", "bash completion script"},
		{"completion", "fish", "fish completion script"},
	} {
		fmt.Fprintf(&b, "complete -c turbo -n '__fish_seen_subcommand_from %s; and test (count (commandline -opc)) -eq 2' -a %s -d '%s'\n", s.cmd, s.word, s.desc)
	}
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from tweaks; and contains -- show (commandline -opc)' -a '(turbo __complete tweaks 2>/dev/null)'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from tweaks; and contains -- list (commandline -opc)' -l all -d 'include tweaks this PC cannot do'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from apply' -a '(turbo __complete tweak-values 2>/dev/null)' -d 'optimization'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from apply' -l dry-run -d 'show the plan, change nothing'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from apply preset undo' -l yes -d 'do not ask for confirmation'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from preset; and test (count (commandline -opc)) -ge 3' -a '(turbo __complete presets 2>/dev/null)'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from preset; and contains -- apply (commandline -opc)' -l dry-run -d 'show the plan, change nothing'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from snapshots; and test (count (commandline -opc)) -ge 3' -a '(turbo __complete snapshots 2>/dev/null)'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from snapshots' -l force -d 'overwrite settings another program changed'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from doctor network snapshots tweaks' -l json -d 'machine-readable output'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from doctor' -l top -d 'include the busiest processes'\n")
	b.WriteString("complete -c turbo -n '__fish_seen_subcommand_from network' -l external -d 'also test an external host'\n")
	return b.String()
}
