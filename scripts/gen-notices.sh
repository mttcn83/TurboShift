#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md from the modules actually linked into
# ./cmd/turbo. Run from the repository root: scripts/gen-notices.sh
set -euo pipefail
out=THIRD_PARTY_NOTICES.md
# The Go distribution's own license (some packagers move it out of GOROOT).
golic=
for f in "$(go env GOROOT)/LICENSE" /usr/share/licenses/go/LICENSE /usr/share/doc/golang*/copyright; do
  [ -f "$f" ] && golic=$f && break
done
[ -n "$golic" ] || { echo "cannot find the Go license text; install it or copy it to GOROOT/LICENSE" >&2; exit 1; }
{
  echo "# Third-party notices"
  echo
  echo "TurboShift itself is MIT licensed (see LICENSE). The \`turbo\` binary links the"
  echo "Go standard library (BSD-3-Clause, https://go.dev/LICENSE) and the modules below."
  echo "Each license text is reproduced as required by its terms."
  echo "This file is generated by scripts/gen-notices.sh and is also built into the"
  echo "binary: run \`turbo licenses\`."
  echo
  echo "---"
  echo
  echo "## Go standard library and runtime ($(go env GOVERSION))"
  echo
  echo '```text'
  cat "$golic"
  echo '```'
  go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' ./cmd/turbo | sort -u | while read -r mod ver; do
    dir=$(go list -m -f '{{.Dir}}' "$mod")
    lic=$(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'COPYING*' \) | sort | head -1)
    echo
    echo "---"
    echo
    echo "## $mod $ver"
    echo
    echo '```text'
    cat "$lic"
    echo '```'
  done
} > "$out"
echo "wrote $out"
